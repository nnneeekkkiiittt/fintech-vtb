// Questions возвращает копию списка вопросов с проставленными ID.
func Questions() []Question {
	result := make([]Question, len(questions))
	for i, q := range questions {
		q.ID = i + 1
		q.Options = append([]string(nil), q.Options...)
		result[i] = q
	}
	return result
}

// ValidateAnswers проверяет, что на каждый вопрос есть ответ, номера вариантов
// существуют, не повторяются, а в вопросах с одним ответом выбран ровно один.
func ValidateAnswers(a Answers) error {
	for n := range a {
		if n < 1 || n > len(questions) {
			return fmt.Errorf("%w: вопроса %d не существует", ErrInvalidAnswers, n)
		}
	}
	for i, q := range questions {
		n := i + 1
		selected := a[n]
		if len(selected) == 0 {
			return fmt.Errorf("%w: нет ответа на вопрос %d", ErrInvalidAnswers, n)
		}
		if !q.Multi && len(selected) != 1 {
			return fmt.Errorf("%w: в вопросе %d нужно выбрать один вариант", ErrInvalidAnswers, n)
		}
		seen := make(map[int]bool, len(selected))
		for _, option := range selected {
			if option < 1 || option > len(q.Options) {
				return fmt.Errorf("%w: в вопросе %d нет варианта %d", ErrInvalidAnswers, n, option)
			}
			if seen[option] {
				return fmt.Errorf("%w: в вопросе %d вариант %d указан дважды", ErrInvalidAnswers, n, option)
			}
			seen[option] = true
		}
	}
	return nil
}
